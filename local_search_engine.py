import math
import re
import nltk
from nltk.stem import PorterStemmer

# Download punctuation dataset for NLTK
nltk.download('punkt', quiet=True)

class LocalSearchEngine:
    def __init__(self, b=0.75, k1=1.5):
        self.stemmer = PorterStemmer()
        self.documents = {}      # Maps doc_id -> original text
        self.index = {}          # Inverted index: {word: {doc_id: term_frequency}}
        self.doc_lengths = {}    # Maps doc_id -> total word count
        self.avg_doc_length = 0  # Average length of all documents
        self.b = b               # BM25 parameter for length normalization
        self.k1 = k1             # BM25 parameter for term frequency scaling

    def _tokenize_and_stem(self, text):
        """Cleans, tokenizes, and stems raw text."""
        text = text.lower()
        # Remove punctuation and split into words
        words = re.findall(r'\b\w+\b', text)
        return [self.stemmer.stem(word) for word in words]

    def add_documents(self, doc_dict):
        """Indexes a dictionary of {doc_id: document_text}."""
        self.documents.update(doc_dict)

        for doc_id, text in doc_dict.items():
            tokens = self._tokenize_and_stem(text)
            self.doc_lengths[doc_id] = len(tokens)

            # Build the inverted index
            for token in tokens:
                if token not in self.index:
                    self.index[token] = {}
                self.index[token][doc_id] = self.index[token].get(doc_id, 0) + 1

        # Recalculate average document length
        self.avg_doc_length = sum(self.doc_lengths.values()) / len(self.doc_lengths)

    def search(self, query, top_n=5):
        """Searches the index using the Okapi BM25 scoring algorithm."""
        query_tokens = self._tokenize_and_stem(query)
        scores = {}
        N = len(self.documents)

        for token in query_tokens:
            if token not in self.index:
                continue

            # Document frequency (number of docs containing the word)
            df = len(self.index[token])

            # Calculate Inverse Document Frequency (IDF)
            idf = math.log((N - df + 0.5) / (df + 0.5) + 1.0)

            # Score each document containing this token
            for doc_id, tf in self.index[token].items():
                doc_len = self.doc_lengths[doc_id]

                # BM25 formula components
                numerator = tf * (self.k1 + 1)
                denominator = tf + self.k1 * (1 - self.b + self.b * (doc_len / self.avg_doc_length))

                # Accumulate score for the document
                scores[doc_id] = scores.get(doc_id, 0.0) + (idf * (numerator / denominator))

        # Sort documents by highest score
        sorted_scores = sorted(scores.items(), key=lambda x: x[1], reverse=True)

        # Format and return results
        results = []
        for doc_id, score in sorted_scores[:top_n]:
            results.append({
                "id": doc_id,
                "score": round(score, 4),
                "text": self.documents[doc_id]
            })
        return results

